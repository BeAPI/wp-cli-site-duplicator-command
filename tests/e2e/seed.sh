#!/usr/bin/env bash
#
# Rebuild a deterministic subdirectory multisite for the e2e tests.
# Runs inside the DDEV web container (see `ddev e2e-seed`). DESTROYS all local data.
#
set -euo pipefail

WP_VERSION="${WP_VERSION:-7.1.4}"
REPO_ROOT="/var/www/html"
DOCROOT="${REPO_ROOT}/tests/wordpress"
MAIN_URL="${DDEV_PRIMARY_URL:?DDEV_PRIMARY_URL is not set, run this script through ddev}"
CHILD_URL="${MAIN_URL}/child"
DOMAIN="${MAIN_URL#https://}"
ADMIN_EMAIL="service+old+wp-cli-site-duplicator-command@beapi.fr"
IMAGE="${REPO_ROOT}/.github/banner-github.png"

cd "${DOCROOT}"

echo "==> WordPress core ${WP_VERSION}"
if [ ! -f wp-load.php ] || [ "$(wp core version 2>/dev/null || true)" != "${WP_VERSION}" ]; then
	wp core download --version="${WP_VERSION}" --locale=en_US --force
fi

echo "==> Reset database, uploads and multisite constants"
for constant in WP_ALLOW_MULTISITE MULTISITE SUBDOMAIN_INSTALL DOMAIN_CURRENT_SITE PATH_CURRENT_SITE SITE_ID_CURRENT_SITE BLOG_ID_CURRENT_SITE; do
	wp config delete "${constant}" --type=constant >/dev/null 2>&1 || true
done
wp db reset --yes
mkdir -p wp-content/uploads
# DDEV mounts the uploads directory, so empty it instead of removing it.
find wp-content/uploads -mindepth 1 -delete

echo "==> Install the network"
wp core multisite-install \
	--url="${MAIN_URL}" \
	--title="Main site" \
	--admin_user=beapi \
	--admin_password=beapi \
	--admin_email="${ADMIN_EMAIL}" \
	--skip-email \
	--skip-config
wp config set WP_ALLOW_MULTISITE true --raw
wp config set MULTISITE true --raw
wp config set SUBDOMAIN_INSTALL false --raw
wp config set DOMAIN_CURRENT_SITE "${DOMAIN}"
wp config set PATH_CURRENT_SITE /
wp config set SITE_ID_CURRENT_SITE 1 --raw
wp config set BLOG_ID_CURRENT_SITE 1 --raw

echo "==> Load the plugin under test as a mu-plugin"
mkdir -p wp-content/mu-plugins
cat > wp-content/mu-plugins/load-site-duplicator.php <<'PHP'
<?php
// Loads the plugin under test from the repository root (generated by tests/e2e/seed.sh).
require_once '/var/www/html/wp-cli-site-duplicator-command.php';
PHP

wp site create --slug=child --title="Child site" --email="${ADMIN_EMAIL}"

# Same fixtures on both sites: users, a custom table, an image and content linking to the site URL.
seed_site() {
	local url="$1" label="$2" role="$3"
	local prefix attachment_id image_url

	wp site empty --yes --url="${url}"
	wp option update timezone_string "Europe/Paris" --url="${url}"
	wp option delete show_avatars --url="${url}" >/dev/null 2>&1 || true

	wp user create "${label}user" "${label}user@example.test" --role="${role}" --porcelain --url="${url}" >/dev/null

	prefix="$(wp db prefix --url="${url}")"
	wp db query "CREATE TABLE \`${prefix}e2e_custom\` (id INT PRIMARY KEY, url VARCHAR(255) NOT NULL)"
	wp db query "INSERT INTO \`${prefix}e2e_custom\` VALUES (1, '${url}/custom-1/'), (2, '${url}/custom-2/')"

	attachment_id="$(wp media import "${IMAGE}" --title="E2E image ${label}" --porcelain --url="${url}")"
	image_url="$(wp eval "echo wp_get_attachment_url( ${attachment_id} );" --url="${url}")"

	wp post create --post_type=post --post_status=publish --post_title="E2E post ${label}" \
		--post_content="<p><a href=\"${url}/sample/\">link</a></p><p><img src=\"${image_url}\" /></p>" \
		--url="${url}"
	wp post create --post_type=page --post_status=publish --post_title="E2E page ${label}" \
		--post_content="<p>${url}/page-link/</p>" \
		--url="${url}"
}

echo "==> Seed the main site"
seed_site "${MAIN_URL}" main editor
# A plugin table whose name looks like a site prefix (e.g. "404 to 301" plugin).
wp db query "CREATE TABLE \`wp_404_e2e_redirects\` (id INT PRIMARY KEY, url VARCHAR(255) NOT NULL)"
wp db query "INSERT INTO \`wp_404_e2e_redirects\` VALUES (1, '${MAIN_URL}/old/')"
# An option whose name starts with the main site prefix but is not prefix-scoped.
wp option update wp_e2e_flag main-flag --url="${MAIN_URL}"

echo "==> Seed the child site"
seed_site "${CHILD_URL}" child author

wp cache flush
wp site list --fields=blog_id,url
echo "==> Seed done"
